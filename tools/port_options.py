#!/usr/bin/env python3
"""Translate a MATLAB controller_options.m (plain assignments) into controller_options.py.

MATLAB scalars initialised for logging (W*p = 0, x_p = [0; 0; 0]) become Python lists, because
the controllers append to them; rotz()/radtodeg() come from matlab_port.
Usage: port_options.py controller_options.m controller_options.py
"""
import re
import sys

LIST_INIT = re.compile(r'^(W\w*|\w+_p|\w+p)$')  # logging arrays: Wxdp, Pf1p, f1_point_p, ...


def translate_value(name, value):
    v = value.strip()
    if v.startswith('['):
        rows = [r.strip() for r in v.strip('[]').split(';') if r.strip()]
        items = [[x for x in re.split(r'[\s,]+', r) if x] for r in rows]
        if len(items) > 1 and all(len(r) == 1 for r in items):      # column vector [0;0;0]
            return '[%s]' % ', '.join(r[0] for r in items)
        if len(items) == 1:
            return '[%s]' % ', '.join(items[0])
        return '[%s]' % ', '.join('[%s]' % ', '.join(r) for r in items)
    if LIST_INIT.match(name) and re.fullmatch(r'-?[\d.eE+-]+', v):
        return '[%s]' % v
    return v.replace('^', '**')


def main(src, dst):
    text = open(src, encoding='latin-1').read().replace('\r\n', '\n')
    out = ['# Python port of %s (generated by tools/port_options.py)' % src.split('/')[-1],
           'from matlab_port import radtodeg, rotz  # noqa: F401', '']
    indexed = {}
    for line in text.split('\n'):
        code, _, comment = line.partition('%')
        comment = ('  # ' + comment.strip()) if comment.strip() else ''
        code = code.strip().rstrip(';').strip()
        if not code:
            out.append(('# ' + line.lstrip('% ').rstrip()) if line.strip() else '')
            continue
        if code == 'format long':
            out.append('# format long')
            continue
        m = re.match(r'^(\w+)\((\d+)\)\s*=\s*(.+)$', code)          # vBody(1)=0
        if m:
            name, idx, value = m.group(1), int(m.group(2)), m.group(3)
            indexed.setdefault(name, {})[idx] = value.strip()
            vals = indexed[name]
            out.append('%s = [%s]%s' % (name, ', '.join(vals.get(i, '0') for i in range(1, max(vals) + 1)), comment))
            continue
        stmts, depth, cur = [], 0, ''
        for ch in code:                     # split on ';' outside brackets only
            depth += (ch == '[') - (ch == ']')
            if ch == ';' and depth == 0:
                stmts.append(cur)
                cur = ''
            else:
                cur += ch
        stmts.append(cur)
        for stmt in [s.strip() for s in stmts if s.strip()]:
            name, value = [p.strip() for p in stmt.split('=', 1)]
            out.append('%s = %s%s' % (name, translate_value(name, value), comment))
            comment = ''
    open(dst, 'w').write('\n'.join(out).rstrip() + '\n')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
